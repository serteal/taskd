export function Octicon({ path, color, size = 14 }: { path: string; color?: string; size?: number }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 16 16"
      fill={color ?? "currentColor"}
      style={{ display: "inline-block", verticalAlign: "text-bottom", flexShrink: 0 }}
      aria-hidden
    >
      <path d={path} />
    </svg>
  );
}

// The row icon for an issue/PR by kind + state.
export function ghStateIcon(kind: string, state: string) {
  const color = COLOR[state] ?? COLOR.open;
  if (state === "closed") return <Octicon path={CLOSED} color={color} />;
  if (kind === "pr") return <Octicon path={state === "merged" ? MERGE : PR} color={color} />;
  return <Octicon path={ISSUE} color={color} />;
}
